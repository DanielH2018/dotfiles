'use strict';
// Pure, deterministic logic for `gen-skill-router`. No fs/process access lives here — the
// wrapper walks the chezmoi SOURCE tree and hands file contents in as plain objects, so
// every function here is a total function of its arguments (config-soak-lib.js's precedent).
//
// Why the SOURCE tree, never ~/.claude: config-soak.json fingerprints
// "the chezmoi SOURCE files ... not the deployed/rendered output" for the same reason this
// generator must — a `--check` that reads a deployed skills dir is green on whichever box
// happens to have chezmoi-applied recently and red in CI (which has no deployed dir at all)
// or on the work laptop, whose overlay adds skills this repo doesn't own.

const { spliceBetween } = require('./gen-lib.js');

const START_MARKER = '<!-- gen-skill-router:start -->';
const END_MARKER = '<!-- gen-skill-router:end -->';

// --- YAML frontmatter, just enough of it ------------------------------------------------
//
// Mirrors vault-tooling/config-map's frontmatter_field (Python): a `---` delimited block,
// `key: value` lines, quoted scalars unwrapped, and the two YAML block-scalar forms this
// repo's skills actually use (`>` folded, used by gh-stack's SKILL.md — multi-line joined
// with spaces). `|`/`|-` (literal, newline-preserving) is included for the same reason
// config-map handles it: a future skill could use it, and silently truncating its
// description to the first line would be a worse failure than the extra few lines here.
function parseFrontmatter(text) {
  if (!text.startsWith('---')) return null;
  const end = text.indexOf('\n---', 3);
  if (end === -1) return null;
  const block = text.slice(3, end).split('\n');
  const fields = {};
  for (let i = 0; i < block.length; i += 1) {
    const line = block[i];
    const m = /^([a-zA-Z_][a-zA-Z0-9_-]*):(.*)$/.exec(line);
    if (!m) continue;
    const key = m[1];
    let value = m[2].trim();
    if (value === '|' || value === '|-' || value === '>' || value === '>-') {
      const isFolded = value[0] === '>';
      const cont = [];
      let j = i + 1;
      for (; j < block.length; j += 1) {
        const contLine = block[j];
        if (contLine.trim() === '') continue;
        if (contLine[0] === ' ' || contLine[0] === '\t') cont.push(contLine.trim());
        else break;
      }
      i = j - 1;
      value = isFolded ? cont.join(' ') : cont.join('\n');
    } else if (value.length >= 2 && value[0] === value[value.length - 1] && (value[0] === '"' || value[0] === "'")) {
      value = value.slice(1, -1);
    }
    fields[key] = value;
  }
  return fields;
}

// skillFiles: { 'skill-dir-name': '<SKILL.md text>' }. Returns [{ name, description }]
// sorted by name — deterministic, no timestamps, so --check is stable across runs.
function collectSkills(skillFiles) {
  const out = [];
  for (const [dir, text] of Object.entries(skillFiles)) {
    const fm = parseFrontmatter(text);
    out.push({ name: dir, description: fm?.description || '(no description in frontmatter)' });
  }
  out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  return out;
}

// --- The generated block itself -----------------------------------------------------------

// The lines between the two marker lines, which injectGenerated keeps.
function renderGeneratedBlock(skills) {
  const lines = [''];
  lines.push('## All installed skills (generated by `bin/gen-skill-router` — do not hand-edit this block)');
  lines.push('');
  for (const s of skills) {
    lines.push(`- **${s.name}** — ${s.description}`);
  }
  lines.push('');
  return lines.join('\n');
}

// Replace the lines strictly between the START_MARKER line and the END_MARKER line (both
// kept) with a freshly rendered block. Throws if the markers are missing or not exactly one
// pair — the generator fills a slot the template declares, it does not invent where that
// slot goes. The splice and its marker checks are gen-lib.js's.
function injectGenerated(templateText, skills) {
  return spliceBetween(templateText, {
    label: 'gen-skill-router',
    begin: { test: (l) => l.includes(START_MARKER), name: START_MARKER },
    end: { test: (l) => l.includes(END_MARKER), name: END_MARKER },
    where: 'the template',
    hint: 'Add them once by hand at the spot the generated skill list should live.',
  }, () => renderGeneratedBlock(skills));
}

// --- Lane-prose drift check ---------------------------------------------------------------
//
// {{ if .work }}...{{ end }} / {{ end -}} gates content that belongs to the WORK overlay
// repo, not this one (to-spec, to-tickets, triage, incident-response, vault-lookup,
// service-context all live there, never here) — stripped before the reference scan so this
// repo's own drift check doesn't fail on a skill it was never going to own. Not a general
// Go-template engine: this repo's router template uses exactly this one construct, and a
// future construct this doesn't handle is a reason to extend it, not a silent miss, because
// an unstripped block just adds MORE tokens to check, never fewer — it fails safe.
const WORK_BLOCK_RE = /\{\{\s*if\s+\.work\s*\}\}[\s\S]*?\{\{\s*end\s*-?\}\}/g;

function stripWorkBlocks(text) {
  return text.replace(WORK_BLOCK_RE, '');
}

// The generated block is correct by construction — it's a description string pulled
// straight from each skill's own frontmatter, which routinely carries backtick spans that
// name arbitrary code (chezmoi-repo-ops's description mentions `node` and `chezmoi diff`,
// neither a skill). Scanning it for "skill references" would flag every such span as
// drift. Strip it before the reference check; injectGenerated regenerates it separately
// and unconditionally, so nothing here needs to validate its own output.
function stripGeneratedBlock(text) {
  const startIdx = text.indexOf(START_MARKER);
  const endIdx = text.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) return text;
  return text.slice(0, startIdx) + text.slice(endIdx + END_MARKER.length);
}

// A backtick span counts as a bare reference worth checking only if it could ONLY be a
// skill/agent slug and nothing else: lowercase kebab-case, no `/` (a command), no `:` (a
// namespaced plugin skill — not owned by this repo, can't be validated from git alone), no
// spaces/paths/punctuation (prose, file paths, placeholders like <pr#>).
const BARE_TOKEN_RE = /`([a-z][a-z0-9]*(?:-[a-z0-9]+)*)`/g;

function extractBareTokens(text) {
  const out = [];
  let m;
  BARE_TOKEN_RE.lastIndex = 0;
  while ((m = BARE_TOKEN_RE.exec(text))) out.push(m[1]);
  return out;
}

// References this repo cannot resolve from its own skills/ or agents/ directories, because
// they name something installed from elsewhere: a plugin skill exposed without a namespace
// prefix, or a built-in skill. Each entry is a deliberate, reviewable exception, not a
// pattern — a real rename of one of THESE must be caught by hand at review time, same as
// today, because there is no git-reproducible source to check it against.
const EXTERNAL_ALLOWLIST = new Set([
  'dataviz', // built-in Claude skill, not under home/private_dot_claude/skills/
  'remember', // remember:remember plugin, referenced unnamespaced in the router prose
  'security-sweep', // global/plugin skill, not under home/private_dot_claude/skills/
  'ops-investigator', // an agent in the WORK overlay repo, not this one's agents/
]);

// Checks the (work-block-stripped) template's bare backtick tokens against the known-good
// set (this repo's own skill dirs + agent files + EXTERNAL_ALLOWLIST). Returns the list of
// tokens that resolve to none of them — the drift the generator must fail on.
function findMissingReferences(strippedText, skillNames, agentNames) {
  const known = new Set([...skillNames, ...agentNames, ...EXTERNAL_ALLOWLIST]);
  const missing = new Set();
  for (const token of extractBareTokens(strippedText)) {
    if (!known.has(token)) missing.add(token);
  }
  return [...missing].sort();
}

module.exports = {
  START_MARKER,
  END_MARKER,
  parseFrontmatter,
  collectSkills,
  renderGeneratedBlock,
  injectGenerated,
  stripWorkBlocks,
  stripGeneratedBlock,
  extractBareTokens,
  findMissingReferences,
  EXTERNAL_ALLOWLIST,
};

'use strict';
// Render launchd plist templates from scheduled/launchd.json. bin/gen-launchd is the CLI;
// everything here is a total function of its arguments.
//
// Why a generator emits XML text itself instead of handing a plist library the job: the
// output is a chezmoi TEMPLATE. Its strings carry `{{ .chezmoi.homeDir }}` and machine-local
// data keys that only `chezmoi execute-template` resolves at activation, so the repo can
// commit the template but never a rendered plist. A library would also escape the `"` in a
// `hasKey . "name"` action. Only & < > are escaped here, and only in element text.
//
// work-laptop-config's gen-launchd.sh renders its own jobs through normalise and value. Its
// plists are plain files, not templates, so it passes suffix '.plist' and writes its own
// header and key order around them.
//
// Job keys. The first group is the schema both repos accept; the second is this repo's:
//   label       required; must equal the plist file name without .plist.tmpl
//   plist       required; repo-relative output path, under scheduled/
//   command     a /bin/zsh -lc string. Exactly one of command and program.
//   calendar    StartCalendarInterval: an object renders a dict, an array an array (even
//               of one); entry keys weekday, hour, minute, day, month; inside an array, a
//               weekday list expands to one entry per day
//   interval    StartInterval, seconds
//   at_load     RunAtLoad; omitted means no key at all, not false
//   keep_alive  KeepAlive
//   why         array of lines, the header comment
//
//   program     the argv, for a job that runs a binary directly rather than through zsh
//   env         EnvironmentVariables, an object of strings, rendered in manifest order
//   throttle    ThrottleInterval, seconds
//   log_path    StandardOutPath and StandardErrorPath, absolute (a template action counts)
//   notes       { "<plist key>" or "env.<name>": [lines] }, a comment above that key, for
//               rationale that belongs to one key rather than to the whole job
// ProcessType is always Background. An unknown key is an error.

const HEADER = [
  'Generated by bin/gen-launchd from scheduled/launchd.json. Edit the manifest, then run',
  'bin/gen-launchd; tests/gen-launchd.test.js fails when this file drifts from it.',
];
const GENERATED_MARK = HEADER[0];

const JOB_KEYS = new Set([
  'label', 'plist', 'command', 'calendar', 'interval', 'at_load', 'keep_alive', 'why',
  'program', 'env', 'throttle', 'log_path', 'notes',
]);
const CALENDAR_KEYS = { weekday: 'Weekday', hour: 'Hour', minute: 'Minute', day: 'Day', month: 'Month' };

function escape(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// An XML comment cannot contain "--" or end in "-"; either would make the plist unparseable.
function checkComment(label, lines) {
  for (const l of lines) {
    if (l.includes('--') || l.endsWith('-')) {
      throw new Error(`gen-launchd: ${label}: comment line cannot contain "--" or end in "-": ${l}`);
    }
  }
}

function calendarEntry(label, e) {
  const out = {};
  for (const [k, v] of Object.entries(e)) {
    if (!CALENDAR_KEYS[k]) throw new Error(`gen-launchd: ${label}: unknown calendar key '${k}'`);
    if (!Number.isInteger(v)) throw new Error(`gen-launchd: ${label}: calendar ${k} must be an integer`);
    out[CALENDAR_KEYS[k]] = v;
  }
  return out;
}

function calendar(label, c) {
  if (Array.isArray(c)) {
    return c.flatMap((e) => (Array.isArray(e.weekday)
      ? e.weekday.map((d) => calendarEntry(label, { ...e, weekday: d }))
      : [calendarEntry(label, e)]));
  }
  if (c && typeof c === 'object') {
    if (Array.isArray(c.weekday)) throw new Error(`gen-launchd: ${label}: a weekday list needs the array form`);
    return calendarEntry(label, c);
  }
  throw new Error(`gen-launchd: ${label}: calendar must be an object or an array`);
}

// Validate one manifest job and return { plist, why, notes, entries }, where entries is the
// ordered list of [plist key, value] pairs the plist carries. `suffix` is the file name
// ending the plist path must have after the label.
function normalise(job, { suffix = '.plist.tmpl' } = {}) {
  const label = job.label;
  if (typeof label !== 'string' || !label) throw new Error('gen-launchd: a job has no label');
  const extra = Object.keys(job).filter((k) => !JOB_KEYS.has(k));
  if (extra.length) throw new Error(`gen-launchd: ${label}: unknown key(s) ${extra.join(', ')}`);
  if (typeof job.plist !== 'string' || !job.plist.endsWith(`/${label}${suffix}`)) {
    throw new Error(`gen-launchd: ${label}: plist must end in /${label}${suffix}`);
  }
  if (('command' in job) === ('program' in job)) {
    throw new Error(`gen-launchd: ${label}: set exactly one of command and program`);
  }
  const argv = 'command' in job ? ['/bin/zsh', '-lc', job.command] : job.program;
  if (!Array.isArray(argv) || !argv.length || argv.some((a) => typeof a !== 'string')) {
    throw new Error(`gen-launchd: ${label}: program must be a non-empty array of strings`);
  }

  const entries = [['Label', label], ['ProgramArguments', argv]];
  if ('env' in job) entries.push(['EnvironmentVariables', job.env]);
  if ('calendar' in job) entries.push(['StartCalendarInterval', calendar(label, job.calendar)]);
  if ('interval' in job) entries.push(['StartInterval', job.interval]);
  if ('at_load' in job) entries.push(['RunAtLoad', job.at_load]);
  if ('keep_alive' in job) entries.push(['KeepAlive', job.keep_alive]);
  if ('throttle' in job) entries.push(['ThrottleInterval', job.throttle]);
  entries.push(['ProcessType', 'Background']);
  if ('log_path' in job) {
    entries.push(['StandardOutPath', job.log_path], ['StandardErrorPath', job.log_path]);
  }

  const notes = job.notes ?? {};
  const known = new Set(entries.map(([k]) => k));
  for (const name of Object.keys(job.env ?? {})) known.add(`env.${name}`);
  for (const [k, lines] of Object.entries(notes)) {
    if (!known.has(k)) throw new Error(`gen-launchd: ${label}: a note names '${k}', which the plist does not have`);
    checkComment(label, lines);
  }
  const why = job.why ?? [];
  checkComment(label, why);
  return { plist: job.plist, why, notes, entries };
}

// The XML lines for one plist value at the given tab depth.
function value(v, indent) {
  const pad = '\t'.repeat(indent);
  if (typeof v === 'string') return [`${pad}<string>${escape(v)}</string>`];
  if (typeof v === 'boolean') return [`${pad}<${v}/>`];
  if (Number.isInteger(v)) return [`${pad}<integer>${v}</integer>`];
  if (Array.isArray(v)) return [`${pad}<array>`, ...v.flatMap((x) => value(x, indent + 1)), `${pad}</array>`];
  if (v && typeof v === 'object') {
    return [`${pad}<dict>`, ...Object.entries(v).flatMap(([k, x]) => pair(k, x, indent + 1)), `${pad}</dict>`];
  }
  throw new Error(`gen-launchd: cannot render ${JSON.stringify(v)}`);
}

// A <key> line, preceded by its note as a comment when it has one.
function keyLines(k, indent, note) {
  const pad = '\t'.repeat(indent);
  const out = [];
  if (note?.length) {
    out.push(`${pad}<!-- ${note[0]}`, ...note.slice(1).map((l) => `${pad}     ${l}`));
    out[out.length - 1] += ' -->';
  }
  return [...out, `${pad}<key>${escape(k)}</key>`];
}

function pair(k, v, indent, note) {
  return [...keyLines(k, indent, note), ...value(v, indent)];
}

// Render one manifest job to the full text of its .plist.tmpl.
function renderJob(job) {
  const { why, notes, entries } = normalise(job);
  const header = [...HEADER, ...(why.length ? ['', ...why] : [])].map((l) => (l ? `  ${l}` : ''));
  const body = entries.flatMap(([k, v]) => {
    if (k !== 'EnvironmentVariables') return pair(k, v, 1, notes[k]);
    const inner = Object.entries(v).flatMap(([n, x]) => {
      if (typeof x !== 'string') throw new Error(`gen-launchd: ${job.label}: env ${n} must be a string`);
      return pair(n, x, 2, notes[`env.${n}`]);
    });
    return [...keyLines(k, 1, notes[k]), '\t<dict>', ...inner, '\t</dict>'];
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!--', ...header, '-->',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    ...body,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

// Render every job: [{ plist, text }] in manifest order. Throws on a duplicate output path.
function renderManifest(manifest) {
  if (!manifest || !Array.isArray(manifest.jobs)) throw new Error('gen-launchd: manifest has no jobs array');
  const seen = new Set();
  return manifest.jobs.map((job) => {
    const text = renderJob(job);
    if (seen.has(job.plist)) throw new Error(`gen-launchd: two jobs write ${job.plist}`);
    seen.add(job.plist);
    return { plist: job.plist, text };
  });
}

module.exports = { renderJob, renderManifest, GENERATED_MARK, normalise, value };
